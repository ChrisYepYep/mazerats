        n: [".....", ".....", "####.", "#...#", "#...#", "#...#", "#...#"],
        o: [".....", ".....", ".###.", "#...#", "#...#", "#...#", ".###."],
        p: [".....", "####.", "#...#", "#...#", "####.", "#....", "#...."],
        q: [".....", ".####", "#...#", "#...#", ".####", "....#", "....#"],
        r: [".....", ".....", "#.##.", "##..#", "#....", "#....", "#...."],
        s: [".....", ".....", ".####", "#....", ".###.", "....#", "####."],
        t: [".#...", ".#...", "####.", ".#...", ".#...", ".#..#", "..##."],
        u: [".....", ".....", "#...#", "#...#", "#...#", "#..##", ".##.#"],
        v: [".....", ".....", "#...#", "#...#", "#...#", ".#.#.", "..#.."],
        w: [".....", ".....", "#...#", "#...#", "#.#.#", "#.#.#", ".#.#."],
