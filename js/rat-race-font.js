        "?": [".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#.."],
        "'": ["..#..", "..#..", ".#...", ".....", ".....", ".....", "....."],
        "-": [".....", ".....", ".....", "#####", ".....", ".....", "....."],
